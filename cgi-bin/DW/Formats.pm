package DW::Formats;

use strict;

our @active_formats = qw( html_casual1 markdown0 html_raw0 rte1 );
our $default_format = 'html_casual1';

# Formats offered when writing a comment. Comments have no rich text editor, so
# rte1 can't be offered there.
our @comment_formats = qw( html_casual1 markdown0 html_raw0 );

# obsolete version => newest version:
our %format_upgrades = ( html_casual0 => 'html_casual1', );

# Retired formats that can no longer be chosen, and the format their content
# opens in when edited. Applied only when reading (an entry being edited, a
# saved preference); never written back, so old content and settings stay
# exactly as stored. Not an upgrade: rte0 content is still rendered as rte0
# (the cleaner treats it as casual HTML), it just has no editor of its own any
# more.
our %format_edit_aliases = ( rte0 => 'rte1', );

# format hashref keys:
# id: identifies formats everywhere, including the HTML cleaner.
# name: displayed in web UI.
# description and features: displayed on /dev/formats.
our %formats = (
    html_casual0 => {
        id          => 'html_casual0',
        name        => "Casual HTML (legacy 0)",
        features    => q{DW tags, auto linebreaks, auto links},

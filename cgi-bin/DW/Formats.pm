# Legacy aliases:
$formats{markdown} = $formats{markdown0};

# Builds items that can be passed to an LJ::html_select for picking a format,
# plus the format that should be initially selected.
# Args: opts hash like (current => "format", preferred => "format", comment => 1).
# Pass comment => 1 when building the menu for a comment; it offers
# @comment_formats instead of @active_formats and ignores preferences for
# formats that comments can't use (rte0, rte1), falling back to the default.
# For entries, a current or preferred retired format (rte0) selects its
# replacement (rte1); the retired format itself is never in the menu.
# Returns: Hashref like {selected => "format", items => [...]}. (Unfortunately,
# LJ::html_select doesn't support just setting selected=true on one of the items,
# so we need to return an extra value.)
sub select_items {
    my %opts    = @_;
    my $comment = $opts{comment} ? 1 : 0;

    # Canonicalize em
    my $current   = validate( $opts{current} );
    my $preferred = validate( $opts{preferred} );

    unless ($comment) {
        $current   = edit_format($current);
        $preferred = edit_format($preferred);
    }

    my @formats  = $comment ? @comment_formats : @active_formats;
    my $selected = $default_format;

    # Use the content's existing format if possible, then fall back to the
    # user's preference (IF it's active or has an active replacement), then the
    # site default.
    if ($current) {
        push( @formats, $current ) unless grep( $_ eq $current, @formats );
        $selected = $current;
    }
    elsif ( $preferred && is_active( $preferred, comment => $comment ) ) {
        $selected = $preferred;
    }
    elsif ( $preferred && is_active( upgrade($preferred), comment => $comment ) ) {
        $selected = upgrade($preferred);
    }

    return {
        selected => $selected,
        items =>
            [ map { { value => $formats{$_}->{id}, text => $formats{$_}->{name}, } } @formats ],
    };
}

# Return the canonical version of the provided format ID if valid, empty string if not.
sub validate {
    my $format = $_[0];
    if ( $format && $formats{$format} ) {
        return $formats{$format}->{id};
    }
    else {
        return '';
    }
}

# Is this format one a person can pick right now? Pass comment => 1 for the
# comment menu's narrower list.
sub is_active {
    my ( $format, %opts ) = @_;
    my @offered = $opts{comment} ? @comment_formats : @active_formats;
    if ( $format && grep( $_ eq $format, @offered ) ) {
        return 1;
    }
    return 0;
}

# The format to edit content in: itself, unless it's retired and has an
# editable replacement (rte0 -> rte1). Read-time only; see %format_edit_aliases.
sub edit_format {
    my $format = validate( $_[0] );
    return $format_edit_aliases{$format} || $format;
}

# Was this format retired in favor of an editable replacement?
sub is_retired {
    my $format = validate( $_[0] );
    return $format && $format_edit_aliases{$format} ? 1 : 0;
}

sub display_name {
    my $format = $_[0];
    if ( $format && $formats{$format} ) {
        return $formats{$format}->{name};
    }
    return "Unknown markup format";
}

# If the provided format ID was replaced by a newer format, return the newest ID
# in its lineage.
sub upgrade {
    my $format = validate( $_[0] );
    return $format_upgrades{$format} || $format;
}

# Convenience aliases for email posts -- these should never be entered into the
# database as an editor prop value, but email posts pass these to validate() as
# a way of asking which format a user currently means if they just said 'html'
# or 'markdown'. (Why not just use 'html' and 'markdown' as the "current"
# aliases? Because 'markdown' is already in use by old email comments.)
$formats{markdown_latest}    = $formats{ upgrade('markdown0') };
$formats{html_casual_latest} = $formats{ upgrade('html_casual1') };
